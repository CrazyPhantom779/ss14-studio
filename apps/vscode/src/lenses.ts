import * as vscode from 'vscode';
import type { GraphIndex } from './indexer.js';

/**
 * Lightweight code lenses that surface SS14 Studio next to the native editor.
 * Nothing opens automatically: each lens is an explicit opt-in action.
 */
export class StudioCodeLensProvider
  implements vscode.CodeLensProvider, vscode.Disposable
{
  private readonly emitter = new vscode.EventEmitter<void>();
  readonly onDidChangeCodeLenses = this.emitter.event;
  private readonly disposables: vscode.Disposable[] = [];

  constructor(private readonly index: GraphIndex) {
    this.disposables.push(
      index.onDidChange(() => this.emitter.fire()),
      index.onDidPrototypesChange(() => this.emitter.fire()),
    );
  }

  refresh(): void {
    this.emitter.fire();
  }

  provideCodeLenses(document: vscode.TextDocument): vscode.CodeLens[] {
    const config = vscode.workspace.getConfiguration('ss14Studio');
    if (!config.get<boolean>('codeLenses', true)) return [];

    const uri = document.uri;
    const text = document.getText();
    const path = uri.fsPath.replaceAll('\\', '/');
    const lenses: vscode.CodeLens[] = [];

    if (/\.ya?ml$/i.test(path)) {
      this.yamlLenses(document, text, lenses);
    } else if (/\.xaml$/i.test(path)) {
      this.xamlLenses(document, text, lenses);
    } else if (/\.xaml\.cs$/i.test(path)) {
      this.codeBehindLenses(uri, lenses);
    } else if (/\/meta\.json$/i.test(path) && /\.rsi\//i.test(path)) {
      this.rsiLenses(document, uri, lenses);
    }

    return lenses;
  }

  private yamlLenses(
    document: vscode.TextDocument,
    text: string,
    lenses: vscode.CodeLens[],
  ): void {
    let graphs = 0;
    try {
      const parsed = this.index.parseText(document.uri, text);
      graphs = parsed.graphs.length;
      for (const graph of parsed.graphs) {
        const line = Math.max(0, Math.min(graph.line - 1, document.lineCount - 1));
        lenses.push(
          new vscode.CodeLens(new vscode.Range(line, 0, line, 0), {
            title: '$(type-hierarchy) Open construction graph in SS14 Studio',
            tooltip: `Visualize ${graph.id} with sprites, recipes and validation`,
            command: 'ss14Studio.openGraph',
            arguments: [graph.key],
          }),
        );
      }
    } catch {
      graphs = 0;
    }

    try {
      const parsed = this.index.parsePrototypeText(document.uri, text);
      const candidates = parsed.prototypes.filter(
        (prototype) => !prototype.abstract || parsed.prototypes.length === 1,
      );
      for (const prototype of candidates) {
        // Graph files already have a dedicated graph lens above.
        if (graphs > 0 && prototype.kind === 'constructionGraph') continue;
        const line = Math.max(
          0,
          Math.min(prototype.line - 1, document.lineCount - 1),
        );
        lenses.push(
          new vscode.CodeLens(new vscode.Range(line, 0, line, 0), {
            title: '$(symbol-class) Open prototype in SS14 Studio',
            tooltip: 'Inspect inheritance, resolved components and partial overlays',
            command: 'ss14Studio.openPrototype',
            arguments: [prototype.id, prototype.kind],
          }),
        );
      }
    } catch {
      // Prototype parsing is best-effort; graph lenses still work.
    }
  }

  private xamlLenses(
    document: vscode.TextDocument,
    text: string,
    lenses: vscode.CodeLens[],
  ): void {
    if (!/<(?:[\w.-]+:)?[\w.-]+[\s>]/.test(text)) return;
    const line = new vscode.Range(0, 0, 0, 0);
    lenses.push(
      new vscode.CodeLens(line, {
        title: '$(preview) Preview in SS14 Studio',
        tooltip: 'Approximate RobustToolbox designer, outline and diagnostics',
        command: 'ss14Studio.openXamlForFile',
      }),
      new vscode.CodeLens(line, {
        title: '$(wand) Clean up XAML',
        tooltip: 'Normalize indentation and remove trailing whitespace',
        command: 'ss14Studio.cleanupXaml',
      }),
    );
    if (!/<!--\s*AutoGenerated/i.test(text)) {
      lenses.push(
        new vscode.CodeLens(line, {
          title: '$(tag) Mark as AutoGenerated',
          tooltip: 'Add the SS14 Studio AutoGenerated marker comment',
          command: 'ss14Studio.markXamlAutoGenerated',
        }),
      );
    }
  }

  private codeBehindLenses(uri: vscode.Uri, lenses: vscode.CodeLens[]): void {
    const xamlPath = uri.fsPath.replace(/\.cs$/i, '');
    lenses.push(
      new vscode.CodeLens(new vscode.Range(0, 0, 0, 0), {
        title: '$(preview) Open linked XAML in SS14 Studio',
        tooltip: xamlPath,
        command: 'ss14Studio.openXamlPath',
        arguments: [xamlPath],
      }),
    );
  }

  private rsiLenses(
    document: vscode.TextDocument,
    uri: vscode.Uri,
    lenses: vscode.CodeLens[],
  ): void {
    lenses.push(
      new vscode.CodeLens(new vscode.Range(0, 0, 0, 0), {
        title: '$(symbol-color) Open RSI Studio',
        tooltip: 'Animate states, inspect metadata and edit sprite sheets',
        command: 'ss14Studio.openRsiForFile',
        arguments: [uri],
      }),
    );
    if (document.lineCount > 0) {
      const states = /"states"\s*:\s*\[/i.exec(document.getText());
      if (states) {
        const offset = document.getText().slice(0, states.index).split('\n').length;
        const line = Math.max(0, Math.min(offset - 1, document.lineCount - 1));
        lenses.push(
          new vscode.CodeLens(new vscode.Range(line, 0, line, 0), {
            title: '$(play) Preview RSI states',
            tooltip: 'Open the animated RSI viewer',
            command: 'ss14Studio.openRsiForFile',
            arguments: [uri],
          }),
        );
      }
    }
  }

  dispose(): void {
    for (const disposable of this.disposables) disposable.dispose();
    this.emitter.dispose();
  }
}
